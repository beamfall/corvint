// MTT-V1-002: the check passes on the generator's own output and fails, naming
// the fix, after a hand edit to a tool description; it writes nothing.
func TestMTTV1002StalenessCheckFailsOnAHandEdit(t *testing.T) {
	out := filepath.Join(t.TempDir(), "MCP-SERVER.md")
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-out", out}, &stdout, &stderr); code != 0 {
		t.Fatalf("write exit %d: %s", code, &stderr)
	}
	if code := run([]string{"-check", "-out", out}, &stdout, &stderr); code != 0 {
		t.Fatalf("check of fresh output exit %d: %s", code, &stderr)
	}
	generated, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	summary := capcatalog.MCPTools()[0].Summary
	if !bytes.Contains(generated, []byte(summary)) {
		t.Fatalf("generated file lacks the first row's description %q", summary)
	}
	edited := bytes.Replace(generated, []byte(summary), []byte(summary+" (hand edit)"), 1)
	if err := os.WriteFile(out, edited, 0o644); err != nil {
		t.Fatal(err)
	}
	stderr.Reset()
	if code := run([]string{"-check", "-out", out}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "is stale") || !strings.Contains(stderr.String(), "make mcp-server-doc") {
		t.Fatalf("check of hand edit exit %d: %s", code, &stderr)
	}
	after, err := os.ReadFile(out)
	if err != nil || !bytes.Equal(after, edited) {
		t.Fatal("the check rewrote the file")
	}
}

// MTT-V1-002: every row reaches the document: each served tool under its
// server with its inputs and errors, and each no-MCP-tool row in its table.
func TestMTTV1002DocumentCarriesEveryRow(t *testing.T) {
	rows := capcatalog.MCPTools()
	document := string(Render(rows))
	if document != string(Render(capcatalog.MCPTools())) {
		t.Fatal("rendering is not deterministic")
	}
	for _, row := range rows {
		if row.Server == capcatalog.ServerNone {
			if !strings.Contains(document, "| `"+row.CLIEquivalent+"` |") {
				t.Fatalf("no-MCP-tool row %s missing", row.Name)
			}
			continue
		}
		if !strings.Contains(document, "### `"+row.Name+"`") {
			t.Fatalf("tool %s has no section", row.Name)
		}
		for _, input := range row.Inputs {
			if !strings.Contains(document, "- Input `"+input.Name+"`: "+input.Description) {
				t.Fatalf("%s input %s missing", row.Name, input.Name)
			}
		}
	}
	if !strings.HasPrefix(document, "<!-- Generated by go run ./tools/mcp-server-doc") {
		t.Fatal("document does not say it is generated")
	}
}

