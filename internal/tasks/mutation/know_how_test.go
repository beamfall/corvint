var (
	khCommit = strings.Repeat("c", 40)
	khBlobA  = strings.Repeat("a", 40)
	khBlobB  = strings.Repeat("b", 40)
)

func khAnchor(path, blob string) wire.Value {
	return obj("blob", str(blob), "path", str(path))
}

// knowHowAdd builds a KNOWHOW_ADD payload; supersedes and reason are "" for
// a fresh note.
func knowHowAdd(text, supersedes, reason string, anchors ...wire.Value) wire.Value {
	return obj("text", str(text), "anchors", wire.Array(anchors...), "routes", wire.Strings([]string{}),
		"commit", str(khCommit), "supersedes", strOrNull(supersedes), "reason", strOrNull(reason),
		"attempt", wire.Null(), "generation", wire.Null(), "evidencePath", wire.Null())
}

// sameExceptKnowHow: a know-how write changes only the ledger and the chain
// fields finalize always rewrites; acceptanceRevision, status and gates stay.
func sameExceptKnowHow(t *testing.T, pre, post *ticket.Record) {
	t.Helper()
	c := *post
	c.KnowHow = pre.KnowHow
	c.Revision, c.PreviousRecordSha256, c.UpdatedAt, c.UpdatedBy = pre.Revision, pre.PreviousRecordSha256, pre.UpdatedAt, pre.UpdatedBy
	if !bytes.Equal(c.Encode(), pre.Encode()) {
		t.Fatalf("know-how write changed the record beyond the ledger:\n%s\n%s", pre.Encode(), post.Encode())
	}
	if post.AcceptanceRevision != pre.AcceptanceRevision || post.Status != pre.Status || fmt.Sprint(post.RequiredGates) != fmt.Sprint(pre.RequiredGates) {
		t.Fatalf("acceptanceRevision/status/gates moved: %s/%s/%v", post.AcceptanceRevision, post.Status, post.RequiredGates)
	}
}

// TestKHNV0003_AddSupersedeRetractKeepHistory: ADD appends a note composed
// from the payload and the trusted binding and clock, supersede is an ADD
// naming an active note with a reason, RETRACT withdraws one; every earlier
// entry stays byte-identical and only the active set moves. A live attempt
// does not block a write, and acceptanceRevision never moves.
func TestKHNV0003_AddSupersedeRetractKeepHistory(t *testing.T) {
	pre := fixture.Ticket("AT-01")
	live := attempts{fixture.TicketID("AT-01"): true}
	post := step(t, owner, live, pre, mutation.OpKnowHowAdd, knowHowAdd("build needs the generated parser first", "", "",
		khAnchor("internal/a.go", khBlobA), khAnchor("internal/b.go", khBlobB)), "1")
	sameExceptKnowHow(t, pre, post)
	if len(post.KnowHow) != 1 {
		t.Fatalf("entries: %+v", post.KnowHow)
	}
	e := post.KnowHow[0]
	if e.Seq != "1" || e.Operation != ticket.KnowHowAdd || e.ActorID != owner.ID || e.ActorRole != "OWNER" || e.RecordedAt != now ||
		e.Commit != khCommit || len(e.Anchors) != 2 || e.Anchors[0].Blob != khBlobA || e.Reason != nil {
		t.Fatalf("entry not composed from the payload and context: %+v", e)
	}
	first := string(wire.Encode(ticket.KnowHowValue(post.KnowHow)))

	sup := step(t, owner, nil, post, mutation.OpKnowHowAdd, knowHowAdd("the parser is generated by make gen", "1", "corrected the command",
		khAnchor("internal/a.go", khBlobA)), "1")
	sameExceptKnowHow(t, post, sup)
	if !strings.HasPrefix(string(wire.Encode(ticket.KnowHowValue(sup.KnowHow))), strings.TrimSuffix(first, "]")) {
		t.Fatal("supersede rewrote the earlier entry")
	}
	if act := ticket.ActiveKnowHow(sup.KnowHow); len(act) != 1 || act[0].Seq != "2" {
		t.Fatalf("active after supersede: %+v", act)
	}

	ret := step(t, owner, nil, sup, mutation.OpKnowHowRetract, obj("note", str("2"), "reason", str("the parser is checked in now")), "1")
	sameExceptKnowHow(t, sup, ret)
	if len(ret.KnowHow) != 3 || ret.KnowHow[2].Operation != ticket.KnowHowRetract || ret.KnowHow[2].Note != "2" || len(ticket.ActiveKnowHow(ret.KnowHow)) != 0 {
		t.Fatalf("retract: %+v", ret.KnowHow)
	}
	back, err := ticket.Decode(ret.Encode())
	if err != nil || !bytes.Equal(back.Encode(), ret.Encode()) {
		t.Fatalf("post record round trip: %v", err)
	}

	// An inactive target (superseded or retracted) is refused.
	refused(t, owner, ret, mutation.OpKnowHowRetract, obj("note", str("1"), "reason", str("again")), mutation.OutcomeValidationFailed, wire.CodeMalformed)
	refused(t, owner, ret, mutation.OpKnowHowAdd, knowHowAdd("x", "2", "again", khAnchor("a.go", khBlobA)), mutation.OutcomeValidationFailed, wire.CodeMalformed)
	refused(t, owner, ret, mutation.OpKnowHowRetract, obj("note", str("9"), "reason", str("never was")), mutation.OutcomeValidationFailed, wire.CodeMalformed)
}

// TestKHNV0003_WriteRefusals: live native home tickets only, OWNER by default
// and OPERATOR by explicit policy row, the 32-entry bound and the CAS.
func TestKHNV0003_WriteRefusals(t *testing.T) {
	ok := knowHowAdd("note", "", "", khAnchor("a.go", khBlobA))
	open := fixture.Ticket("AT-01")
	d := wire.Sum([]byte("log"))
	draft := fixture.Ticket("AT-01")
	draft.Status = ticket.StatusDraft
	step(t, owner, nil, draft, mutation.OpKnowHowAdd, ok, "1")
	held := step(t, owner, nil, open, mutation.OpHold, obj("holdId", str("h"), "reason", str("wait")), "1")
	step(t, owner, nil, held, mutation.OpKnowHowAdd, ok, "1")
	for name, rec := range map[string]*ticket.Record{
		"ARCHIVED":  step(t, owner, nil, open, mutation.OpArchive, obj("reason", str("gone")), "1"),
		"COMPLETED": step(t, owner, nil, open, mutation.OpCompleteManual, obj("evidence", wire.Strings([]string{string(d)}), "reason", str("done")), "2"),
	} {
		t.Run("status "+name, func(t *testing.T) {
			refused(t, owner, rec, mutation.OpKnowHowAdd, ok, mutation.OutcomeBlocked, wire.CodeTicketState)
		})
	}
	imported := fixture.Ticket("AT-01")
	src := "X-1"
	imported.Source = ticket.Source{Kind: "IMPORT", SourceQueueID: "queue:ext:src", SourceItemID: &src}
	refused(t, owner, imported, mutation.OpKnowHowAdd, ok, mutation.OutcomeBlocked, wire.CodeTicketState)

	full := fixture.Ticket("AT-01")
	for i := 0; i < wire.KnowHowMaxEntries; i++ {
		full.KnowHow = append(full.KnowHow, ticket.KnowHowEntry{Seq: wire.CountOf(int64(i + 1)), Operation: ticket.KnowHowAdd, Text: "n",
			Anchors: []ticket.KnowHowAnchor{{Path: "a.go", Blob: khBlobA}}, Routes: []string{}, Commit: khCommit, ActorID: "russell", ActorRole: "OWNER", RecordedAt: now})
	}
	if _, err := ticket.Decode(full.Encode()); err != nil {
		t.Fatalf("thirty-two entries: %v", err)
	}
	refused(t, owner, full, mutation.OpKnowHowAdd, ok, mutation.OutcomeValidationFailed, wire.CodeLimitExceeded)

	for _, b := range []mutation.Binding{operator, worker, reviewer, importer, system} {
		refused(t, b, open, mutation.OpKnowHowAdd, ok, mutation.OutcomeUnauthorized, "")
	}
	rev := string(open.Revision)
	pv := fixture.PolicyValue()
	pv.Obj.Set("roles", obj("OPERATOR", wire.Strings([]string{"KNOWHOW_ADD", "KNOWHOW_RETRACT"})))
	ctx := ctxWithPolicy(t, operator, nil, wire.EncodeFile(pv), open)
	plan := apply(t, ctx, envelope("op1", operator, "AT-01", rev, mutation.OpKnowHowAdd, ok))
	want(t, plan, mutation.OutcomeCompleted, "")
	if plan.Post.KnowHow[0].ActorID != operator.ID || plan.Post.KnowHow[0].ActorRole != "OPERATOR" {
		t.Fatalf("operator entry actor: %+v", plan.Post.KnowHow)
	}
	pv.Obj.Set("roles", obj("WORKER", wire.Strings([]string{"KNOWHOW_ADD"})))
	if _, err := intent.DecodePolicy(wire.EncodeFile(pv)); err == nil {
		t.Fatal("a WORKER row naming KNOWHOW_ADD was admitted")
	}

	ctx = newCtx(t, owner, nil, open)
	want(t, apply(t, ctx, envelope("cas", owner, "AT-01", "7", mutation.OpKnowHowAdd, ok)), mutation.OutcomeRevisionConflict, "")
}

// TestKHNV0002_PayloadRefusals: the closed payload refuses absolute, '..'
// and directory anchors, unsorted or duplicate anchors, oversize text, more
// than four anchors or routes, and a reason without supersedes (or the
// reverse).
func TestKHNV0002_PayloadRefusals(t *testing.T) {
	rev := string(fixture.Ticket("AT-01").Revision)
	five := []wire.Value{}
	for _, p := range []string{"a", "b", "c", "d", "e"} {
		five = append(five, khAnchor(p+".go", khBlobA))
	}
	routes := func(rs ...string) wire.Value {
		p := knowHowAdd("t", "", "", khAnchor("a.go", khBlobA))
		p.Obj.Set("routes", wire.Strings(rs))
		return p
	}
	cases := map[string]wire.Value{
		"absolute anchor":   knowHowAdd("t", "", "", khAnchor("/etc/passwd", khBlobA)),
		"dotdot anchor":     knowHowAdd("t", "", "", khAnchor("../x.go", khBlobA)),
		"directory anchor":  knowHowAdd("t", "", "", khAnchor("internal/", khBlobA)),
		"no anchors":        knowHowAdd("t", "", ""),
		"unsorted anchors":  knowHowAdd("t", "", "", khAnchor("b.go", khBlobA), khAnchor("a.go", khBlobA)),
		"duplicate anchors": knowHowAdd("t", "", "", khAnchor("a.go", khBlobA), khAnchor("a.go", khBlobB)),
		"five anchors":      knowHowAdd("t", "", "", five...),
		"bad blob":          knowHowAdd("t", "", "", khAnchor("a.go", "00")),
		"oversize text":     knowHowAdd(strings.Repeat("x", wire.KnowHowMaxTextBytes+1), "", "", khAnchor("a.go", khBlobA)),
		"blank text":        knowHowAdd("   ", "", "", khAnchor("a.go", khBlobA)),
		"reason alone":      knowHowAdd("t", "", "why", khAnchor("a.go", khBlobA)),
		"supersedes alone":  knowHowAdd("t", "1", "", khAnchor("a.go", khBlobA)),
		"five routes":       routes("r1", "r2", "r3", "r4", "r5"),
		"unsorted routes":   routes("r2", "r1"),
		"long route":        routes(strings.Repeat("r", wire.KnowHowMaxRouteBytes+1)),
		"unknown key":       obj("text", str("t"), "extra", str("x")),
	}
	for name, p := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := mutation.Decode(envelope("p", owner, "AT-01", rev, mutation.OpKnowHowAdd, p)); err == nil {
				t.Fatalf("payload decoded: %s", wire.Encode(p))
			}
		})
	}
	if _, err := mutation.Decode(envelope("p", owner, "AT-01", rev, mutation.OpKnowHowRetract, obj("note", str("1")))); err == nil {
		t.Fatal("a retract without a reason decoded")
	}
}

// TestKHNV0004_SecretScreenRefusesTheWrite: a secret in the text, a
// supersede or retract reason, a route or an anchor path is refused with the
// owned SECRET_DETECTED code (KHN-V0-010, not MALFORMED) and the retained
// KNOWHOW_SECRET_DETECTED detail prefix (KHN-V0-011), and the detail never
// repeats the secret.
func TestKHNV0004_SecretScreenRefusesTheWrite(t *testing.T) {
	secret := "AKIAABCDEFGHIJKLMNOP"
	if !secretscreen.MatchString(secret) {
		t.Fatal("fixture is not a screened secret")
	}
	base := step(t, owner, nil, fixture.Ticket("AT-01"), mutation.OpKnowHowAdd, knowHowAdd("ok", "", "", khAnchor("a.go", khBlobA)), "1")
	withRoute := knowHowAdd("ok", "", "", khAnchor("a.go", khBlobA))
	withRoute.Obj.Set("routes", wire.Strings([]string{secret}))
	cases := map[string]struct {
		op string
		p  wire.Value
	}{
		"text":           {mutation.OpKnowHowAdd, knowHowAdd("key is "+secret, "", "", khAnchor("a.go", khBlobA))},
		"supersede why":  {mutation.OpKnowHowAdd, knowHowAdd("ok", "1", "rotated "+secret, khAnchor("a.go", khBlobA))},
		"retract reason": {mutation.OpKnowHowRetract, obj("note", str("1"), "reason", str("leaked "+secret))},
		"anchor path":    {mutation.OpKnowHowAdd, knowHowAdd("ok", "", "", khAnchor("keys/"+secret+".txt", khBlobA))},
		"route":          {mutation.OpKnowHowAdd, withRoute},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			ctx := newCtx(t, owner, nil, base)
			plan := apply(t, ctx, envelope("sec", owner, "AT-01", string(base.Revision), c.op, c.p))
			want(t, plan, mutation.OutcomeValidationFailed, wire.CodeSecretDetected)
			if plan.Outcome.HasCode(wire.CodeMalformed) || !strings.HasPrefix(plan.Detail, mutation.KnowHowSecretDetail+":") || strings.Contains(plan.Detail, secret) || plan.Post != nil && len(plan.Post.KnowHow) != 1 {
				t.Fatalf("secret refusal detail %q", plan.Detail)
			}
		})
	}
}

// TestKHNV0003_AdoptFileRefusesKnowHow: a hand-edited intent file cannot
// add, rewrite or drop know-how entries.
func TestKHNV0003_AdoptFileRefusesKnowHow(t *testing.T) {
	added := fixture.Ticket("AT-01")
	written := step(t, owner, nil, fixture.Ticket("AT-01"), mutation.OpKnowHowAdd, knowHowAdd("n", "", "", khAnchor("a.go", khBlobA)), "1")
	cases := map[string]struct {
		canonical *ticket.Record
		edit      func(*ticket.Record)
	}{
		"add":     {added, func(r *ticket.Record) { r.KnowHow = append([]ticket.KnowHowEntry{}, written.KnowHow...) }},
		"drop":    {written, func(r *ticket.Record) { r.KnowHow = nil }},
		"rewrite": {written, func(r *ticket.Record) { r.KnowHow[0].Text = "edited" }},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			before := string(c.canonical.Encode())
			ctx := newCtx(t, owner, nil, c.canonical)
			plan := adopt(t, ctx, c.canonical, fileOf(t, c.canonical, c.edit))
			want(t, plan, mutation.OutcomeValidationFailed, wire.CodeAdoptUnsupportedField)
			if !strings.Contains(plan.Detail, "knowHow") || len(plan.Composed) != 0 {
				t.Fatalf("not refused as a protected field: %q %v", plan.Detail, plan.Composed)
			}
			stillDiverged(t, plan, c.canonical, before)
		})
	}
}

// TestKHNV0002_RecordCodecRefusals: the ledger is omitted when empty and
// its seq, target and reason relationships hold on decode.
func TestKHNV0002_RecordCodecRefusals(t *testing.T) {
	if bytes.Contains(fixture.Ticket("AT-01").Encode(), []byte(`"knowHow"`)) {
		t.Fatal("a record without notes gained the key")
	}
	add := func(seq string) ticket.KnowHowEntry {
		return ticket.KnowHowEntry{Seq: wire.Count(seq), Operation: ticket.KnowHowAdd, Text: "n", Anchors: []ticket.KnowHowAnchor{{Path: "a.go", Blob: khBlobA}},
			Routes: []string{}, Commit: khCommit, ActorID: "russell", ActorRole: "OWNER", RecordedAt: now}
	}
	reason := "r"
	one := wire.Count("1")
	sup := add("2")
	sup.Supersedes, sup.Reason = &one, &reason
	ret := ticket.KnowHowEntry{Seq: "2", Operation: ticket.KnowHowRetract, Note: "1", Reason: &reason, ActorID: "russell", ActorRole: "OWNER", RecordedAt: now}
	noReason := sup
	noReason.Reason = nil
	strayReason := add("1")
	strayReason.Reason = &reason
	ret3 := ret
	ret3.Seq = "3"
	worker := add("1")
	worker.ActorRole = "WORKER"
	retNoReason := ret
	retNoReason.Reason = nil
	cases := map[string][]ticket.KnowHowEntry{
		"seq gap":             {add("2")},
		"supersede no reason": {add("1"), noReason},
		"reason no supersede": {strayReason},
		"retract twice":       {add("1"), ret, ret3},
		"forward target":      {ret},
		"worker actor":        {worker},
		"retract no reason":   {add("1"), retNoReason},
	}
	for name, entries := range cases {
		t.Run(name, func(t *testing.T) {
			rec := fixture.Ticket("AT-01")
			rec.KnowHow = entries
			if _, err := ticket.Decode(rec.Encode()); err == nil || !strings.Contains(err.Error(), "/knowHow") {
				t.Fatalf("decoded %s with %v; want a knowHow refusal", rec.Encode(), err)
			}
		})
	}
	empty := fixture.Ticket("AT-01").Value()
	empty.Obj.Set("knowHow", wire.Array())
	if _, err := ticket.Decode(wire.EncodeFile(empty)); err == nil {
		t.Fatal("an empty knowHow array decoded")
	}
}

