// cypress drives `cypress run` in a Chromium browser through a generated
// configuration that wraps the project's own (LPCV-V0-975). Cypress does not
// start the application, so the collector starts Options.Server.
type cypress struct {
	wrapper string // generated config, root-relative
}

const (
	cyWrapper = "corvint-browsercov.config.cjs"
	cySupport = "corvint-browsercov.support.js"
)

func (y *cypress) version(_ context.Context, c *collector) (string, error) {
	return packageVersion(c.Root, "cypress")
}

func (y *cypress) serves(*collector) bool { return false }

// prepare writes the wrapper configuration and support file beside the
// project's configuration, refusing to replace a file it did not write.
func (y *cypress) prepare(c *collector) error {
	if y.wrapper != "" {
		return nil
	}
	if c.Browser == "" {
		return fmt.Errorf("browsercov: cypress needs a Chromium-family --browser (a name such as chrome, or a path); Electron has no DevTools port to read coverage from")
	}
	config := c.Config
	if config == "" {
		for _, n := range []string{"cypress.config.js", "cypress.config.cjs", "cypress.config.mjs", "cypress.config.ts"} {
			if _, err := os.Stat(filepath.Join(c.Root, n)); err == nil {
				config = n
				break
			}
		}
	}
	if config == "" {
		return fmt.Errorf("browsercov: no cypress.config.{js,cjs,mjs} under %s", c.Root)
	}
	if strings.HasSuffix(config, ".ts") {
		return fmt.Errorf("browsercov: %s: a TypeScript Cypress configuration is not supported; compile it to JavaScript", config)
	}
	cfgDir := filepath.Dir(filepath.Join(c.Root, filepath.FromSlash(config)))
	wrapper, support := filepath.Join(cfgDir, cyWrapper), filepath.Join(cfgDir, cySupport)
	body := fmt.Sprintf("// Generated by corvint browsercov for one collection; removed when it ends.\n"+
		"module.exports = require(process.env.CORVINT_BROWSERCOV_HOOK).cypressConfig(require(%q), require(\"path\").join(__dirname, %q));\n",
		"./"+filepath.Base(config), cySupport)
	for _, f := range []string{wrapper, support} {
		h, err := os.OpenFile(f, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if err != nil {
			return fmt.Errorf("browsercov: %v (remove a stale file left by an interrupted collection)", err)
		}
		h.Close()
		c.cleanup = append(c.cleanup, f)
		c.repo.Generated = append(c.repo.Generated, f)
	}
	if err := os.WriteFile(wrapper, []byte(body), 0o644); err != nil {
		return err
	}
	rel, _ := filepath.Rel(c.Root, wrapper)
	y.wrapper = filepath.ToSlash(rel)
	return nil
}

// cypressRun runs `cypress run` once and returns each spec's browser file.
func (y *cypress) cypressRun(ctx context.Context, c *collector, dir string, env []string, args ...string) ([]browserFile, error) {
	args = append([]string{"run", "--config-file", y.wrapper, "--browser", c.Browser}, args...)
	cmd := c.command(ctx, dir, "cypress", args...)
	cmd.Env = append(cmd.Env, env...)
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	runErr := runGroup(cmd)
	if ctx.Err() != nil {
		return nil, ctx.Err()
	}
	entries, _ := os.ReadDir(dir)
	var files []browserFile
	for _, e := range entries {
		if !strings.HasPrefix(e.Name(), "browser-") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		var b browserFile
		if err := json.Unmarshal(body, &b); err != nil {
			return nil, fmt.Errorf("browsercov: %s: %v", e.Name(), err)
		}
		files = append(files, b)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("browsercov: cypress ran no spec (%v): %s", runErr, tail(out.Bytes()))
	}
	// A failing test explains a non-zero exit; anything else (a throwing
	// after:spec handler, a crashed renderer) fails the run.
	if runErr != nil && !anyFailed(files) {
		return nil, fmt.Errorf("browsercov: cypress failed though no test did (%v): %s", runErr, tail(out.Bytes()))
	}
	return files, nil
}

// rootRel names an absolute spec path Cypress reports relative to the root.
// Cypress resolves specs against its project root, which is the working
// directory, not the configuration's directory; it may report the root with
// symbolic links resolved.
func rootRel(root, abs string) (string, error) {
	for _, r := range []string{root, ""} {
		if r == "" {
			var err error
			if r, err = filepath.EvalSymlinks(root); err != nil {
				break
			}
		}
		rel, err := filepath.Rel(r, filepath.FromSlash(abs))
		if err == nil && filepath.IsAbs(abs) && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return filepath.ToSlash(rel), nil
		}
	}
	return "", fmt.Errorf("browsercov: cypress spec %s is outside %s", abs, root)
}

func anyFailed(files []browserFile) bool {
	for _, b := range files {
		for _, t := range b.Tests {
			if t.State == "failed" {
				return true
			}
		}
	}
	return false
}

func (y *cypress) specs(ctx context.Context, c *collector) ([]string, error) {
	if err := y.prepare(c); err != nil {
		return nil, err
	}
	dir, err := c.newDir()
	if err != nil {
		return nil, err
	}
	// The listing run skips every test, so it executes none of them.
	err = c.invoke(ctx, dir, func(rctx context.Context) error {
		_, err := y.cypressRun(rctx, c, dir, []string{"CYPRESS_CORVINT_LIST=1"})
		return err
	})
	if err != nil {
		return nil, err
	}
	body, err := os.ReadFile(filepath.Join(dir, "specs.json"))
	if err != nil {
		return nil, fmt.Errorf("browsercov: cypress listed no specs: %v", err)
	}
	var specs []string
	if err := json.Unmarshal(body, &specs); err != nil {
		return nil, err
	}
	for i, s := range specs {
		if specs[i], err = rootRel(c.Root, s); err != nil {
			return nil, err
		}
	}
	sort.Strings(specs)
	return specs, nil
}

func (y *cypress) run(ctx context.Context, c *collector, dir, spec string, only *result) ([]result, error) {
	var env []string
	if only != nil {
		title, _ := json.Marshal(only.key.([]string))
		env = append(env, "CYPRESS_CORVINT_ONLY="+url.QueryEscape(string(title)))
	}
	files, err := y.cypressRun(ctx, c, dir, env, "--spec", filepath.Join(c.Root, filepath.FromSlash(spec)))
	if err != nil {
		return nil, err
	}
	var out []result
	for _, b := range files {
		got, err := rootRel(c.Root, b.Spec)
		if err != nil {
			return nil, err
		}
		if got != spec {
			return nil, fmt.Errorf("browsercov: running %s also ran %s", spec, got)
		}
		for _, t := range b.Tests {
			state := t.State
			if state != "passed" && state != "failed" {
				state = "skipped" // pending, skipped
			}
			out = append(out, result{Name: strings.Join(t.Title, " > "), State: state, key: t.Title})
		}
	}
	return out, nil
}
