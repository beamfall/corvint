// TestImpactWithholdsUnverifiableADRAuthority pins `CF-V0-031` and `CF-V0-032` on
// the oracle-shared `impact` surface. `Impact(index, paths, limit)` receives only
// the change set the caller declares and no revision the caller did not author, so
// it cannot establish that a cited decision is independent of the change it is
// describing. The clause admits exactly two dispositions for such a surface, and
// this one reports rather than claims: the citation stays, with confidence `low`
// and authority `unverified-contract`, and the abstention is named.
//
// The refusal is deliberately unconditional. A predicate over `paths` would
// downgrade an honest caller who declares the decision it touched and would never
// touch an attacker, who reaches this code through the ledger record's `adr:`
// field and simply omits the path -- a control that closes nothing, which
// `CF-V0-025` forbids asserting.
func TestImpactWithholdsUnverifiableADRAuthority(t *testing.T) {
	root := impactRepository(t, "")
	index, err := Build(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	receipt, err := Impact(index, []string{"internal/token/token.go"}, 20)
	if err != nil {
		t.Fatal(err)
	}
	cited := 0
	for _, entry := range anySlice(receipt["results"]) {
		for _, item := range anySlice(entry.(map[string]any)["evidence"]) {
			record := item.(map[string]any)
			if record["path"] != "docs/adr/0012-token.md" {
				if record["authority"] == "accepted-contract" || record["authority"] == "partially-superseded-contract" {
					t.Fatalf("impact asserted accepted authority it cannot verify: %v", record)
				}
				continue
			}
			cited++
			if record["authority"] != UnverifiedContractAuthority || record["confidence"] != "low" {
				t.Fatalf("cited decision keeps unverifiable authority: %v", record)
			}
			if record["reason"] != "ADR-0012 governs feature:stream-token" {
				t.Fatalf("withholding rewrote the citation itself: %v", record)
			}
		}
	}
	if cited == 0 {
		t.Fatal("fixture no longer reaches the ADR authority branch, so it discriminates nothing")
	}
	// CF-V0-032 (decision 0101) words the entry exactly and places it first.
	const withheld = "ADR-0012 governs feature:stream-token: no caller-independent revision is available at which to resolve the cited decision status, so accepted authority is withheld"
	uncertainty := anySlice(receipt["coverage"].(map[string]any)["uncertainty"])
	if len(uncertainty) == 0 || uncertainty[0] != withheld {
		t.Fatalf("abstention is not named in the CF-V0-032 form: %v", uncertainty)
	}
}

