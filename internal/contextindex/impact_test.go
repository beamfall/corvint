func TestImpactCompilesFullGoPathResultClosure(t *testing.T) {
	root := impactRepository(t, "")
	index, err := Build(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	receipt, err := Impact(index, []string{"internal/token/token.go"}, 20)
	if err != nil {
		t.Fatal(err)
	}
	kinds := make(map[string]bool)
	for _, raw := range anySlice(receipt["results"]) {
		item := raw.(map[string]any)
		kinds[stringValue(item["kind"])] = true
	}
	for _, kind := range []string{"path", "test", "reference", "reverse-import", "feature", "scenario", "spec"} {
		if !kinds[kind] {
			t.Errorf("missing %s result; kinds=%v", kind, kinds)
		}
	}
	resultIDs := make(map[string]bool)
	for _, raw := range anySlice(receipt["results"]) {
		item := raw.(map[string]any)
		resultIDs[stringValue(item["id"])] = true
	}
	if !resultIDs["web/caller.ts"] {
		t.Fatalf("non-Go reverse importer missing; ids=%v", resultIDs)
	}
	encoded, err := CanonicalJSON(receipt)
	if err != nil {
		t.Fatal(err)
	}
	coverage := receipt["coverage"].(map[string]any)
	if coverage["packet_bytes"] != len(encoded) {
		t.Fatalf("packet_bytes=%v encoded=%d", coverage["packet_bytes"], len(encoded))
	}
}

func resultKeys(receipt map[string]any) []string {
	result := make([]string, 0)
	for _, raw := range anySlice(receipt["results"]) {
		item := raw.(map[string]any)
		result = append(result, stringValue(item["kind"])+":"+stringValue(item["id"]))
	}
	return result
}

