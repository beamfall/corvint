func TestMergeEvidenceAllocationRatchet(t *testing.T) {
	candidate := map[string]any{"evidence": evidenceBenchmarkItems(5, 10)}
	allocations := testing.AllocsPerRun(100, func() {
		runtime.KeepAlive(mergeEvidenceBenchmarkFixture(candidate))
	})
	if allocations > 16 {
		t.Fatalf("merge evidence allocations=%.0f want <=16", allocations)
	}
	result := testing.Benchmark(BenchmarkMergeEvidence)
	if bytes := result.AllocedBytesPerOp(); bytes > 2200 {
		t.Fatalf("merge evidence bytes/op=%d want <=2200", bytes)
	}
	if allocations := result.AllocsPerOp(); allocations > 15 {
		t.Fatalf("merge evidence allocs/op=%d want <=15", allocations)
	}
	if restored := testing.AllocsPerRun(100, func() {
		runtime.KeepAlive(mergeEvidenceWithSetBenchmarkFixture(candidate))
	}); restored <= 16 {
		t.Fatalf("restored merge evidence allocations=%.0f want >16", restored)
	}
}

