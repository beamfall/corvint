// TestImpactCoverageDenominatesTheAdmittedUniverse proves that `omitted_results`
// counts the results the ranking ceiling dropped, not the zero that a receipt
// reports when it measures its own truncated output.  Coverage has to be
// denominated in the universe admitted for abstention to mean anything: a
// consumer reading `omitted_results: 0` must be able to conclude that nothing
// was dropped, which is only sound while `requested_results` names the
// pre-truncation count.
func TestImpactCoverageDenominatesTheAdmittedUniverse(t *testing.T) {
	root := impactRepository(t, "")
	index, err := Build(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	admitted, err := Impact(index, []string{"internal/token/token.go"}, maxLimit)
	if err != nil {
		t.Fatal(err)
	}
	universe := len(anySlice(admitted["results"]))
	limit := universe - 2
	if limit < 1 {
		t.Fatalf("fixture ranks %d results, too few to truncate", universe)
	}
	truncated, err := Impact(index, []string{"internal/token/token.go"}, limit)
	if err != nil {
		t.Fatal(err)
	}
	coverage := truncated["coverage"].(map[string]any)
	if coverage["requested_results"] != universe {
		t.Fatalf("requested_results = %v, want the %d admitted results", coverage["requested_results"], universe)
	}
	if coverage["included_results"] != limit {
		t.Fatalf("included_results = %v, want %d", coverage["included_results"], limit)
	}
	if coverage["omitted_results"] != universe-limit {
		t.Fatalf("omitted_results = %v, want the %d results the ranking ceiling dropped", coverage["omitted_results"], universe-limit)
	}
}

// TestImpactAdmitsPythonPathsWithoutAGoModule pins decision 0015: the Go
// module is a precondition for .go paths only; a .py path in a module-free
// repository resolves its reverse importers as the oracle does.
func TestImpactAdmitsPythonPathsWithoutAGoModule(t *testing.T) {
	root := t.TempDir()
	if command := testGitOptional(t, root, "init", "-q"); command != "" {
		t.Skipf("git init unsupported: %s", command)
	}
	testGit(t, root, "config", "user.email", "corvint@example.test")
	testGit(t, root, "config", "user.name", "Corvint Test")
	files := map[string]string{
		"src/pkg/__init__.py": "VERSION = \"1\"\n",
		"src/pkg/engine.py":   "def run() -> str:\n    return \"engine\"\n",
		"tools/dotted.py":     "from src.pkg.engine import run\n\n\ndef main() -> str:\n    return run()\n",
		"tools/main.go":       "package main\n\nfunc main() {}\n",
	}
	for relative, content := range files {
		writeTestFile(t, root, relative, content)
	}
	testGit(t, root, "add", ".")
	testGit(t, root, "commit", "-qm", "module-free python fixture")
	index, err := Build(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	receipt, err := Impact(index, []string{"src/pkg/engine.py"}, 10)
	if err != nil {
		t.Fatalf("python path without module: %v", err)
	}
	ids := make([]string, 0)
	for _, raw := range anySlice(receipt["results"]) {
		ids = append(ids, raw.(map[string]any)["id"].(string))
	}
	if strings.Join(ids, ",") != "src/pkg/engine.py,tools/dotted.py" {
		t.Fatalf("results = %v", ids)
	}
	var unsupported *Error
	if _, err := Impact(index, []string{"tools/main.go"}, 10); !errors.As(err, &unsupported) || unsupported.Code != "unsupported-impact-repository" {
		t.Fatalf("go path without module: %v", err)
	}
	if _, err := Impact(index, []string{"src/pkg/engine.py", "tools/main.go"}, 10); !errors.As(err, &unsupported) || unsupported.Code != "unsupported-impact-repository" {
		t.Fatalf("mixed paths without module: %v", err)
	}
}
