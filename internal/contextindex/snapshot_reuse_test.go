// reuseFixtureFiles exercises every per-source fact the reuse regroups:
// grammar and lexer refusals, markers, approximate and grammar imports,
// extraction notes, undecodable bytes, a generated header, an empty file,
// upper-case extensions and a document that names other sources.
func reuseFixtureFiles() map[string]string {
	return map[string]string{
		"go.mod":            "module example.test/reuse\n\ngo 1.27.0\n",
		"app/app.go":        "package app\n\nimport \"fmt\"\n\n// feature:reuse-one\nfunc Run() string { return fmt.Sprint(\"first\") }\n",
		"app/app_test.go":   "package app\n\n// scenario:reuse-two\nfunc TestRun() { _ = Run() }\n",
		"app/broken.go":     "package app\n\nfunc {\n",
		"app/Upper.GO":      "package app\n\nimport \"strings\"\n\nfunc Upper() string { return strings.ToUpper(\"x\") }\n",
		"lib/good.py":       "import os\n\ndef good():\n    return os.sep\n",
		"lib/bad.py":        "def (:\n",
		"lib/UP.PY":         "import sys\n",
		"web/view.ts":       "import { a } from \"./model\";\n// feature:reuse-one\nexport const b = a;\n",
		"web/model.ts":      "export const a = 1;\n",
		"web/Comp.TSX":      "import React from \"react\";\nexport const C = () => null;\n",
		"web/open.ts":       "const s = `unterminated\n",
		"gen/gen.go":        "// Code generated by fixture. DO NOT EDIT.\n\npackage gen\n",
		"data/binary.txt":   "\xff\xfe\x00broken",
		"data/empty.txt":    "",
		"docs/guide.md":     "# Guide\n\nRun `app/app.go` and `app/added.go`.\n",
		"docs/old.md":       "# Old\n\nSee `old/removed.go`.\n",
		"old/removed.go":    "package old\n\nfunc Removed() {}\n",
		"testing/notes.txt": "scenario:reuse-two\n",
	}
}

func TestSnapshotReuseMatchesColdBuild(t *testing.T) {
	qualifyDefaultPath(t)
	source := impactRepositoryWithFiles(t, reuseFixtureFiles())
	prior := testGit(t, source, "rev-parse", "HEAD")
	writeTestFile(t, source, "app/app.go", "package app\n\nimport \"os\"\n\n// feature:reuse-three\nfunc Run() string { return os.Args[0] }\n")
	writeTestFile(t, source, "app/added.go", "package app\n\nfunc Added() {}\n")
	writeTestFile(t, source, "web/model.ts", "import { c } from \"./other\";\nexport const a = c;\n")
	testGit(t, source, "rm", "-q", "old/removed.go")
	testGit(t, source, "mv", "lib/good.py", "lib/moved.py")
	testGit(t, source, "add", ".")
	testGit(t, source, "update-index", "--chmod=+x", "data/empty.txt")
	testGit(t, source, "commit", "-qm", "move ahead")
	target := testGit(t, source, "rev-parse", "HEAD")
	reindexed := qualifyColdAndIncremental(t, source, prior, target)
	// Unchanged admitted, non-generated sources minus the moved one; the
	// re-moded empty file is reused under its new mode.
	if want := len(reindexed.Sources) - 4; reindexed.reusedSources != want {
		t.Fatalf("IDX-SNAP-V0-037: reused %d of %d sources, want %d", reindexed.reusedSources, len(reindexed.Sources), want)
	}
	if mode := reindexed.Sources["data/empty.txt"].Mode; mode != "100755" {
		t.Fatalf("IDX-SNAP-V0-037: reused source kept mode %q", mode)
	}
	t.Run("no-change re-index reuses every source", func(t *testing.T) {
		root := cloneAtRevision(t, source, target)
		writeTreeSnapshot(t, root)
		before := canonicalSnapshotBytes(t, root)
		again, _ := writeTreeSnapshot(t, root)
		if again.reusedSources != len(again.Sources) {
			t.Fatalf("IDX-SNAP-V0-037: no-change re-index reused %d of %d", again.reusedSources, len(again.Sources))
		}
		if !bytes.Equal(before, canonicalSnapshotBytes(t, root)) {
			t.Fatal("IDX-SNAP-V0-037: no-change re-index changed the served index")
		}
	})
}

// TestSnapshotReuseRefusesUnverifiedPrior: a prior source whose bytes no
// longer hash to its blob id is pinned again, and an undecodable prior is not
// used at all; either way the served index is the cold one.
func TestSnapshotReuseRefusesUnverifiedPrior(t *testing.T) {
	qualifyDefaultPath(t)
	source := impactRepositoryWithFiles(t, reuseFixtureFiles())
	target := testGit(t, source, "rev-parse", "HEAD")
	cold := cloneAtRevision(t, source, target)
	t.Setenv("CORVINT_INDEX_REUSE", "0")
	writeTreeSnapshot(t, cold)
	t.Setenv("CORVINT_INDEX_REUSE", "")
	coldBytes := canonicalSnapshotBytes(t, cold)

	t.Run("tampered source bytes", func(t *testing.T) {
		root := cloneAtRevision(t, source, target)
		built, err := BuildForSnapshot(context.Background(), root)
		if err != nil {
			t.Fatal(err)
		}
		tampered := built.Sources["app/app.go"]
		tampered.Data = bytes.Replace(append([]byte(nil), tampered.Data...), []byte("first"), []byte("FIRST"), 1)
		built.Sources["app/app.go"] = tampered
		if _, err := WriteSnapshot(built); err != nil {
			t.Fatal(err)
		}
		again, _ := writeTreeSnapshot(t, root)
		if again.reusedSources != len(again.Sources)-1 {
			t.Fatalf("IDX-SNAP-V0-037: reused %d of %d with one tampered source", again.reusedSources, len(again.Sources))
		}
		if !bytes.Equal(coldBytes, canonicalSnapshotBytes(t, root)) {
			t.Fatal("IDX-SNAP-V0-037: tampered prior reached the served index")
		}
	})
	t.Run("truncated prior", func(t *testing.T) {
		root := cloneAtRevision(t, source, target)
		_, receipt := writeTreeSnapshot(t, root)
		if err := os.Truncate(receipt.Path, receipt.Bytes/2); err != nil {
			t.Fatal(err)
		}
		again, _ := writeTreeSnapshot(t, root)
		if again.reusedSources != 0 {
			t.Fatalf("IDX-SNAP-V0-037: reused %d sources from a truncated prior", again.reusedSources)
		}
		if !bytes.Equal(coldBytes, canonicalSnapshotBytes(t, root)) {
			t.Fatal("IDX-SNAP-V0-037: truncated prior changed the served index")
		}
	})
}

// TestMergeReusedPostingsEqualsFullInversion: renumbering a prior inversion
// and merging the fresh sources' postings into it gives the table a full
// inversion of the new source set writes, key for key and count for count.
func TestMergeReusedPostingsEqualsFullInversion(t *testing.T) {
	terms := func(seed int) sourceTerms {
		counts := map[string]uint32{}
		words := map[string]struct{}{}
		for i := 0; i < 1+seed%5; i++ {
			key := fmt.Sprintf("k%d", (seed*7+i*3)%11)
			counts[key] += uint32(1 + i)
			words[key] = struct{}{}
		}
		return sourceTerms{terms: counts, words: words, pathTerms: []string{fmt.Sprintf("p%d", seed%4)}}
	}
	// Prior sources 0..9 with seeds 0..9; the new set drops 2 and 7, keeps the
	// rest unchanged, and inserts fresh sources with new seeds between them.
	prior := make([]sourceTerms, 10)
	for i := range prior {
		prior[i] = terms(i)
	}
	type slot struct {
		old  int // -1 for a fresh source
		seed int
	}
	layout := []slot{{0, 0}, {-1, 20}, {1, 1}, {3, 3}, {4, 4}, {-1, 21}, {-1, 22}, {5, 5}, {6, 6}, {8, 8}, {9, 9}, {-1, 23}}
	remap := []int32{0, 2, -1, 3, 4, 7, 8, -1, 9, 10}
	full := make([]sourceTerms, len(layout))
	fresh := make([]sourceTerms, len(layout))
	for position, item := range layout {
		full[position] = terms(item.seed)
		if item.old < 0 {
			fresh[position] = terms(item.seed)
		}
	}
	words := func(s sourceTerms) map[string]struct{} { return s.words }
	pathTerms := func(s sourceTerms) map[string]struct{} { return stringSetOf(s.pathTerms) }
	for _, check := range []struct {
		name         string
		prior, fresh termPostings
		want         termPostings
		counted      bool
	}{
		{"terms", invertCounts(prior), invertCounts(fresh), invertCounts(full), true},
		{"words", invertPresence(prior, words), invertPresence(fresh, words), invertPresence(full, words), false},
		{"path terms", invertPresence(prior, pathTerms), invertPresence(fresh, pathTerms), invertPresence(full, pathTerms), false},
	} {
		got := mergeReusedPostings(check.prior, remap, check.fresh, check.counted)
		if err := check.prior.canonical(); err != nil {
			t.Fatalf("%s: prior not canonical: %v", check.name, err)
		}
		gotJSON, _ := json.Marshal(got)
		wantJSON, _ := json.Marshal(check.want)
		if !bytes.Equal(gotJSON, wantJSON) || !reflect.DeepEqual(got.KeyOffsets, check.want.KeyOffsets) {
			t.Fatalf("IDX-SNAP-V0-037 %s: merged %s, full inversion %s", check.name, gotJSON, wantJSON)
		}
	}
}

// TestSnapshotReuseRefusesRowsBoundToOtherBlobs: a prior whose checksum is
// valid but whose symbol, marker or refusal row carries a blob id other than
// its source's is refused whole, so no row cites bytes it was not derived
// from, and the served index is the cold one.
func TestSnapshotReuseRefusesRowsBoundToOtherBlobs(t *testing.T) {
	qualifyDefaultPath(t)
	source := impactRepositoryWithFiles(t, reuseFixtureFiles())
	target := testGit(t, source, "rev-parse", "HEAD")
	cold := cloneAtRevision(t, source, target)
	t.Setenv("CORVINT_INDEX_REUSE", "0")
	writeTreeSnapshot(t, cold)
	t.Setenv("CORVINT_INDEX_REUSE", "")
	coldBytes := canonicalSnapshotBytes(t, cold)
	for _, corrupt := range []struct {
		name  string
		apply func(*Index, string) bool
	}{
		{"symbol", func(index *Index, other string) bool {
			for position, symbol := range index.Symbols {
				if symbol.Path == "app/app.go" {
					index.Symbols[position].BlobHash = other
					return true
				}
			}
			return false
		}},
		{"marker", func(index *Index, other string) bool {
			for _, markers := range index.Markers {
				for position, marker := range markers {
					if marker.Path == "app/app.go" {
						markers[position].BlobHash = other
						return true
					}
				}
			}
			return false
		}},
		{"refusal", func(index *Index, other string) bool {
			for position, refusal := range index.Unparsed {
				if refusal.Path == "app/broken.go" {
					index.Unparsed[position].BlobHash = other
					return true
				}
			}
			return false
		}},
		{"import refusal", func(index *Index, other string) bool {
			for position, refusal := range index.Unparsed {
				if refusal.Path == "web/open.ts" && refusal.Facts == "imports" {
					index.Unparsed[position].BlobHash = other
					return true
				}
			}
			return false
		}},
	} {
		t.Run(corrupt.name, func(t *testing.T) {
			root := cloneAtRevision(t, source, target)
			built, err := BuildForSnapshot(context.Background(), root)
			if err != nil {
				t.Fatal(err)
			}
			if !corrupt.apply(built, built.Sources["lib/good.py"].BlobHash) {
				t.Fatalf("fixture has no %s row to corrupt", corrupt.name)
			}
			if _, err := WriteSnapshot(built); err != nil {
				t.Fatal(err)
			}
			again, _ := writeTreeSnapshot(t, root)
			if again.reusedSources != 0 {
				t.Fatalf("IDX-SNAP-V0-037: reused %d sources from a prior with a %s row bound to another blob", again.reusedSources, corrupt.name)
			}
			if !bytes.Equal(coldBytes, canonicalSnapshotBytes(t, root)) {
				t.Fatalf("IDX-SNAP-V0-037: a %s row bound to another blob reached the served index", corrupt.name)
			}
		})
	}
}

// identGraphEdges names each undirected identifier-graph edge by its two
// source paths.
func identGraphEdges(t *testing.T, index *Index) map[[2]string]struct{} {
	t.Helper()
	graph := index.Vocabulary.IdentGraph
	if graph == nil || graph.Bounded {
		t.Fatal("identifier graph missing or bounded")
	}
	edges := map[[2]string]struct{}{}
	for node := uint32(0); node < graph.Nodes; node++ {
		for _, target := range graph.Targets[graph.Offsets[node]:graph.Offsets[node+1]] {
			left, right := index.Vocabulary.Paths[node], index.Vocabulary.Paths[target]
			if left > right {
				left, right = right, left
			}
			edges[[2]string{left, right}] = struct{}{}
		}
	}
	return edges
}

// TestSnapshotReuseRecomputesIdentGraphForUnchangedReferrers: a reused,
// unchanged file that names an identifier loses its edge when the definition
// moves to another file and gains one to the new definer, as a cold build
// derives it.
func TestSnapshotReuseRecomputesIdentGraphForUnchangedReferrers(t *testing.T) {
	qualifyDefaultPath(t)
	source := impactRepositoryWithFiles(t, map[string]string{
		"go.mod":          "module example.test/graph\n\ngo 1.27.0\n",
		"graph/def.go":    "package graph\n\nfunc ComputeTotal() int { return 1 }\n",
		"graph/helper.go": "package graph\n\nfunc HelperValue() int { return 2 }\n",
		"graph/use.go":    "package graph\n\nfunc Caller() int { return ComputeTotal() + HelperValue() }\n",
	})
	prior := testGit(t, source, "rev-parse", "HEAD")
	baseline, err := Build(context.Background(), cloneAtRevision(t, source, prior))
	if err != nil {
		t.Fatal(err)
	}
	before := identGraphEdges(t, baseline)
	useDef, useHelper, useMoved := [2]string{"graph/def.go", "graph/use.go"}, [2]string{"graph/helper.go", "graph/use.go"}, [2]string{"graph/moved.go", "graph/use.go"}
	if _, ok := before[useDef]; !ok {
		t.Fatalf("baseline graph lacks the use/def edge: %v", before)
	}
	if _, ok := before[useHelper]; !ok {
		t.Fatalf("baseline graph lacks the use/helper edge: %v", before)
	}
	writeTestFile(t, source, "graph/def.go", "package graph\n\nfunc ComputeSum() int { return 1 }\n")
	writeTestFile(t, source, "graph/moved.go", "package graph\n\nfunc ComputeTotal() int { return 3 }\n")
	testGit(t, source, "add", ".")
	testGit(t, source, "commit", "-qm", "move the definition")
	target := testGit(t, source, "rev-parse", "HEAD")
	reindexed := qualifyColdAndIncremental(t, source, prior, target)
	if want := len(reindexed.Sources) - 2; reindexed.reusedSources != want {
		t.Fatalf("IDX-SNAP-V0-037: reused %d of %d sources, want %d", reindexed.reusedSources, len(reindexed.Sources), want)
	}
	after := identGraphEdges(t, reindexed)
	if _, ok := after[useDef]; ok {
		t.Fatalf("IDX-SNAP-V0-037: the reused referrer kept its edge to the removed definition: %v", after)
	}
	if _, ok := after[useMoved]; !ok {
		t.Fatalf("IDX-SNAP-V0-037: the reused referrer has no edge to the new definer: %v", after)
	}
	if _, ok := after[useHelper]; !ok {
		t.Fatalf("IDX-SNAP-V0-037: the unchanged use/helper edge is gone: %v", after)
	}
}
