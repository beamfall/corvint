// The fallback ran whenever no Exclusion matched, so it blamed a suffix even
// for a path that has none. Invariant 2 forbids stating a cause the code has
// not established.
func TestSubjectEvidenceGapNamesOnlyTheCauseItEstablished(t *testing.T) {
	recorded := &taskContextCompiler{
		index:   &Index{Exclusions: []Exclusion{{Path: "cache/gen.go", Reason: "generated source"}}},
		subject: "cache/gen.go",
	}
	if got := recorded.subjectEvidenceGap(); got != "generated source" {
		t.Fatalf("recorded exclusion = %q, want the recorded reason", got)
	}
	unadmitted := &taskContextCompiler{index: &Index{}, subject: "legacy/Legacy.java"}
	if got := unadmitted.subjectEvidenceGap(); !strings.Contains(got, "suffix") {
		t.Fatalf("unadmitted suffix = %q, want the suffix named", got)
	}
	// LICENSE, Dockerfile and script/* have no suffix to blame.
	bare := &taskContextCompiler{index: &Index{}, subject: "LICENSE"}
	got := bare.subjectEvidenceGap()
	if got == "" || strings.Contains(got, "suffix") {
		t.Fatalf("extension-less subject = %q, want a non-empty gap that claims no suffix cause", got)
	}
}

// An unpinnable nearest claim (TCP-V0-016) must disclose why its blob_hash
// is empty the same way a result row does (TCP-V0-003), rather than leaving
// the empty hash unexplained (AGENTS.md invariant 2).
func TestAnswerabilityPacketDisclosesAnUnpinnedNearestClaim(t *testing.T) {
	verdict := answerability{
		terms:   []specificTerm{{term: "httpRetry"}, {term: "maxAttempts"}},
		nearest: []nearestClaim{{path: "legacy/Legacy.java", supports: []string{}, lacks: []string{"httpRetry"}}},
	}
	packet := verdict.packet(&Index{Sources: map[string]Source{}})
	if packet["verdict"] != "unsupported-conjunction" {
		t.Fatalf("verdict = %v, want unsupported-conjunction", packet["verdict"])
	}
	claims := mapsFromAny(packet["nearest_claims"])
	if len(claims) != 1 || claims[0]["blob_hash"] != "" {
		t.Fatalf("nearest claims = %v, want one claim with an empty blob_hash", claims)
	}
	if gap, ok := claims[0]["evidence_gap"].(string); !ok || gap == "" {
		t.Fatalf("unpinned nearest claim evidence_gap = %v, want a non-empty explanation", claims[0])
	}
}
