func taskContextFixture(t *testing.T) *Index {
	t.Helper()
	root := impactRepositoryWithFiles(t, map[string]string{
		"go.mod":                   "module example.test/fixture\n\ngo 1.27.0\n",
		"cache/cache.go":           "package cache\n\nfunc Demux() string { return \"demux\" }\n",
		"cache/demux.go":           "package cache\n\nfunc Split(key string) string { return key }\n",
		"cache/demux_test.go":      "package cache\n\nfunc TestSplit() { _ = Split(\"k\") }\n",
		"cache/notes.md":           "# cache\n\nThe cache demuxes keys.\n",
		"server/server.go":         "package server\n\nimport \"example.test/fixture/cache\"\n\nfunc Run() string { return cache.Demux() }\n",
		"docs/unrelated.md":        "# nothing\n\nirrelevant prose\n",
		"pkg/other/other.go":       "package other\n\nfunc Other() {}\n",
		"testing/features.yaml":    "features: []\n",
		"cache/README.md":          "cache package\n",
		"cache/gen.go":             "// Code generated by fixture. DO NOT EDIT.\n\npackage cache\n\nfunc Gen() {}\n",
		"legacy/Legacy.groovy":     "package legacy;\n\npublic class Legacy {}\n",
		"legacy/LegacyTest.groovy": "package legacy;\n\npublic class LegacyTest {}\n",
	})
	index, err := Build(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	return index
}

func contextRowsByKind(t *testing.T, packet map[string]any) map[string][]string {
	t.Helper()
	found := map[string][]string{}
	for _, item := range mapsFromAny(packet["results"]) {
		found[item["kind"].(string)] = append(found[item["kind"].(string)], item["id"].(string))
	}
	return found
}
