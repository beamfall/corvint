func contextRowsByKind(t *testing.T, packet map[string]any) map[string][]string {
	t.Helper()
	found := map[string][]string{}
	for _, item := range mapsFromAny(packet["results"]) {
		found[item["kind"].(string)] = append(found[item["kind"].(string)], item["id"].(string))
	}
	return found
}

func TestTaskContextKeepsTheSubjectOutOfTheResults(t *testing.T) {
	index := taskContextFixture(t)
	packet, err := TaskContext(context.Background(), index, "Reviewer asks whether `Split` handles empty keys in cache/demux.go", "cache/demux.go", 20)
	if err != nil {
		t.Fatal(err)
	}
	if packet["state"] != "READY" {
		t.Fatalf("state = %v", packet["state"])
	}
	subject := packet["subject"].(map[string]any)
	if subject["path"] != "cache/demux.go" {
		t.Fatalf("subject = %v", subject)
	}
	found := contextRowsByKind(t, packet)
	for kind, ids := range found {
		for _, id := range ids {
			if id == "cache/demux.go" {
				t.Fatalf("subject appears as a %s result", kind)
			}
		}
	}
	if len(found["pair"]) == 0 || found["pair"][0] != "cache/demux_test.go" {
		t.Fatalf("pair rows = %v, want the test counterpart first", found["pair"])
	}
	// The fixture's one commit co-changes every file and cache.go names the
	// subject's stem, so the cache siblings arrive through an earlier slot
	// (reference or cochange); one of the three must carry them.
	for _, sibling := range []string{"cache/cache.go", "cache/notes.md"} {
		if !slices.Contains(found["reference"], sibling) && !slices.Contains(found["cochange"], sibling) && !slices.Contains(found["sibling"], sibling) {
			t.Fatalf("sibling %s absent: %v", sibling, found)
		}
	}
}

