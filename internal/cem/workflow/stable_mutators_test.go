// stableMutatorMap is the public sealed positive cem/1.0 map: real stable bytes,
// so every refusal below is of a document the stable verifier admits.
const stableMutatorMap = "../../../protocol/cem-1.0/stable/repository-envelope-packet/inherited/fixtures/maps/sha1-positive-sealed.json"

func stableMapBytes(t *testing.T) []byte {
	t.Helper()
	data, err := os.ReadFile(stableMutatorMap)
	if err != nil {
		t.Fatal(err)
	}
	if !wire.DeclaresStable(data) {
		t.Fatal("fixture does not declare cem/1.0")
	}
	return data
}

// requireStableRefusal asserts the explicit stable mutator refusal and that the
// stable bytes at relative are unchanged.
func requireStableRefusal(t *testing.T, err error, tool, root, relative string, want []byte) {
	t.Helper()
	if cemcode.CodeOf(err) != cemcode.NotAProducerMap {
		t.Fatalf("%s: got %v, want %s", tool, err, cemcode.NotAProducerMap)
	}
	message := cemcode.MessageOf(err)
	for _, fragment := range []string{"cem/1.0", "cem " + tool, "Core mutates only a producer map", "cem status or cem verify"} {
		if !strings.Contains(message, fragment) {
			t.Errorf("%s: refusal %q does not name %q", tool, message, fragment)
		}
	}
	got, readErr := os.ReadFile(filepath.Join(root, filepath.FromSlash(relative)))
	if readErr != nil || !bytes.Equal(got, want) {
		t.Fatalf("%s: the stable map at %s changed (%v)", tool, relative, readErr)
	}
}

// CEM-V1-030: prepare never overwrites a stable sidecar that carries criteria,
// receipts, links, artifacts or provenance: without --replace it refuses the
// unbound resume, with --replace the stable refusal, and it publishes no patch
// cache when it refuses.
func TestPrepareRefusesStableSidecar(t *testing.T) {
	t.Parallel()
	stable := stableMapBytes(t)
	for _, replace := range []bool{false, true} {
		root, base, target := makeRepo(t)
		writeFile(t, root, wire.ExcludedCEMPath, string(stable))
		session := openSession(t, root)
		_, err := session.Prepare(ctx(), PrepareOptions{Base: base, Target: target, Replace: replace})
		if replace {
			requireStableRefusal(t, err, "prepare", root, wire.ExcludedCEMPath, stable)
		} else if cemcode.CodeOf(err) != cemcode.MapUnavailable {
			t.Fatalf("resume over a bound stable sidecar: %v", err)
		}
		requireUntouched(t, root, wire.ExcludedCEMPath, stable)
		if _, statErr := os.Lstat(filepath.Join(session.gitRoot.Path(), filepath.FromSlash(defaultPatchRelative))); !os.IsNotExist(statErr) {
			t.Fatalf("replace=%v: refusal published the patch cache (%v)", replace, statErr)
		}
	}
}

// CEM-V1-033: an existing candidate-profile or other-spec map keeps the earlier
// prepare refusal and is still regenerated by an explicit --replace.
func TestPrepareNonStableExistingMapUnchanged(t *testing.T) {
	t.Parallel()
	for _, existing := range []string{
		`{"spec": "` + wire.CandidateSpec + `"}`,
		`{"spec": "cem/1.0 "}`,
		`{"spec": "cem/9.9"}`,
	} {
		root, base, target := makeRepo(t)
		writeFile(t, root, wire.ExcludedCEMPath, existing)
		_, err := openSession(t, root).Prepare(ctx(), PrepareOptions{Base: base, Target: target})
		if cemcode.CodeOf(err) != cemcode.MapUnavailable || cemcode.GuidanceOf(err) != "the existing map is not a valid CEM document; pass --replace to regenerate" {
			t.Fatalf("%s: got %v (guidance %q)", existing, err, cemcode.GuidanceOf(err))
		}
		prepared, err := openSession(t, root).Prepare(ctx(), PrepareOptions{Base: base, Target: target, Replace: true})
		if err != nil || prepared["resumed"] != false {
			t.Fatalf("%s: explicit replace failed: %v", existing, err)
		}
	}
}

func stableMutators() map[string]func(*Session, string, string) error {
	return map[string]func(*Session, string, string) error{
		"cite": func(session *Session, input, output string) error {
			_, err := session.Cite(ctx(), CiteOptions{
				MapPath: input, Hunk: "1", EvidencePath: "docs/rule.txt",
				Lines: "1:1", Relation: "specification", Output: output,
			})
			return err
		},
		"mark": func(session *Session, input, output string) error {
			_, err := session.Mark(ctx(), MarkOptions{
				MapPath: input, Hunk: "1", Disposition: "unknown",
				Reason: "insufficient-evidence", Output: output,
			})
			return err
		},
		"cover": func(session *Session, input, output string) error {
			_, err := session.Cover(ctx(), CoverOptions{
				MapPath: input, Coverprofile: "cover.out", TestRun: "go test ./...", Output: output,
			})
			return err
		},
		"discriminate": func(session *Session, input, output string) error {
			_, err := session.Discriminate(ctx(), DiscriminateOptions{MapPath: input, Target: "HEAD", Output: output})
			return err
		},
	}
}

// CEM-V1-031: cite, mark, cover and discriminate refuse a cem/1.0 input
// explicitly, in place and with a separate output, and write nothing.
func TestMutatorsRefuseStableInput(t *testing.T) {
	t.Parallel()
	stable := stableMapBytes(t)
	for tool, mutate := range stableMutators() {
		for _, output := range []string{"", "out.cem.json"} {
			root, _, _ := makeRepo(t)
			writeFile(t, root, "stable.cem.json", string(stable))
			err := mutate(openSession(t, root), "stable.cem.json", output)
			requireStableRefusal(t, err, tool, root, "stable.cem.json", stable)
			if output != "" {
				if _, statErr := os.Lstat(filepath.Join(root, output)); !os.IsNotExist(statErr) {
					t.Fatalf("%s: refusal wrote %s (%v)", tool, output, statErr)
				}
			}
		}
	}
}

// CEM-V1-031: no Core map writer replaces an existing cem/1.0 document named as
// its output, even when its own producer input is valid.
func TestMutatorsRefuseStableDestination(t *testing.T) {
	t.Parallel()
	stable := stableMapBytes(t)
	for tool, mutate := range stableMutators() {
		root, base, target := makeRepo(t)
		if _, err := openSession(t, root).Prepare(ctx(), PrepareOptions{Base: base, Target: target}); err != nil {
			t.Fatal(err)
		}
		writeFile(t, root, "stable.cem.json", string(stable))
		err := mutate(openSession(t, root), wire.ExcludedCEMPath, "stable.cem.json")
		requireStableRefusal(t, err, tool, root, "stable.cem.json", stable)
	}
	root, base, target := makeRepo(t)
	prepared, err := openSession(t, root).Prepare(ctx(), PrepareOptions{Base: base, Target: target})
	if err != nil {
		t.Fatal(err)
	}
	patchBytes, err := os.ReadFile(prepared["patch"].(string))
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, root, "exact.patch", string(patchBytes))
	writeFile(t, root, wire.ExcludedCEMPath, string(stable))
	_, err = openSession(t, root).Begin(ctx(), BeginOptions{PatchPath: "exact.patch", Base: base, Output: wire.ExcludedCEMPath})
	requireStableRefusal(t, err, "begin", root, wire.ExcludedCEMPath, stable)
}

