// AMAP-V0-217: a substitution may spell one or more whole path segments; the literal text before
// it must fit the first segment it covers and the text after it the last.
func TestAMAPV0217MultiSegmentSubstitution(t *testing.T) {
	tmpl := func(p string) []string {
		segs, ok := templateSegments(p, ':', '*')
		if !ok {
			t.Fatalf("template %s", p)
		}
		return segs
	}
	call := func(u string) []string {
		c := &endpointCall{}
		if r := c.setURL(strings.ReplaceAll(u, "{}", substMark)); r != "" {
			t.Fatalf("%s: %s", u, r)
		}
		return c.segs
	}
	for _, tc := range []struct {
		tmpl, url string
		want      bool
	}{
		{"/api/clubs/:id/settings", "/api/{}", true},
		{"/api/clubs/:id/settings", "/api/{}/settings", true},
		{"/api/clubs/:id/settings", "/api/c{}/settings", true},
		{"/api/clubs/:id/settings", "/api/x{}/settings", false},
		{"/api/clubs/:id/settings", "/api/{}s/x", false},
		{"/api/clubs/:id/settings", "/api/{}ings", true},
		{"/api/clubs/:id/settings", "/api/{}/{}", true},
		{"/api/clubs/:id/settings", "/api/{}/clubs/{}/settings", false},
		{"/api/clubs", "/api/clubs/{}", false},
		{"/files/*rest", "/{}", true},
		{"/orders/new", "/orders/{}", true},
		{"/orders/new", "/orders/{}/new", false},
	} {
		if got := segmentsReach(tmpl(tc.tmpl), call(tc.url)); got != tc.want {
			t.Errorf("%s <- %s: %v, want %v", tc.tmpl, tc.url, got, tc.want)
		}
	}
}

// AMAP-V0-218: a request interceptor and a generated client are unknown with a reason; a generated
// file's calls are not read, and a generator header in a file naming no request API is ignored.
func TestAMAPV0218InterceptorsAndGeneratedClients(t *testing.T) {
	for src, want := range map[string]string{
		"axios.interceptors.request.use(f); axios.get('/a');":                             "! request-interceptor-not-modelled;GET /a",
		"app.config(function ($httpProvider) { $httpProvider.interceptors.push('x'); });": "! request-interceptor-not-modelled",
		"/* Generated by orval */\nexport const list = () => fetch('/api/a');":            "! generated-client-not-modelled Generated by orval",
		"// @generated by openapi-generator\naxios.get('/api/a');":                        "! generated-client-not-modelled openapi-generator",
		"// @generated\nexport const routes = ['/a'];":                                    "",
		"// NSwag\nclass C { constructor(http: HttpClient) {} }":                          "! generated-client-not-modelled NSwag",
		strings.Repeat(" ", 2100) + "// @generated\nfetch('/a');":                         "GET /a",
	} {
		calls, notes := scanCalls("f.js", []byte(src))
		got := []string{}
		for _, n := range notes {
			s := "! " + n.Reason
			if strings.HasPrefix(n.Reason, "generated") {
				s += " " + n.Detail
			}
			got = append(got, s)
		}
		for _, c := range calls {
			got = append(got, c.Verb+" "+c.URL)
		}
		if strings.Join(got, ";") != want {
			t.Errorf("%q: got %q, want %q", src, got, want)
		}
	}
}

// AMAP-V0-219: a block-style YAML OpenAPI document is read as its JSON form would be; every YAML
// form outside the subset refuses the document with the line and why.
func TestAMAPV0219OpenAPIYAML(t *testing.T) {
	doc := `# api
---
openapi: "3.0.3"
servers:
  - url: https://api.example.com/v2   # production
    description: prod
paths:
  /teesheets/{date}:
    parameters:
      - name: date
        in: path
    get:
      operationId: getTeesheet
      responses:
        '200':
          description: 'it''s ok'
  "/slots":
    post:
      operationId: "createSlot"
`
	rows, reason, detail := openAPIEndpoints("o.yaml", []byte(doc))
	if reason != "" || len(rows) != 2 || rows[0].Verb != "POST" || rows[0].Path != "/v2/slots" || rows[0].Operation != "createSlot" ||
		rows[1].Path != "/v2/teesheets/{date}" || rows[1].Operation != "getTeesheet" || rows[1].Declaration != "o.yaml#/paths/~1teesheets~1{date}/get" {
		t.Fatalf("%q %q %+v", reason, detail, rows)
	}
	for src, want := range map[string]string{
		"openapi: 3.0.0\npaths: {}\n":                                     "line 2: flow collection",
		"openapi: 3.0.0\nx: &a 1\npaths:\n  /a:\n    get: *a\n":           "line 2: anchor or alias",
		"openapi: 3.0.0\ninfo:\n  description: |\n    text\npaths:\n":     "line 3: block scalar",
		"openapi: 3.0.0\ninfo:\n  title: a\n   b\npaths:\n":               "line 4: unexpected indentation or multi-line scalar",
		"openapi: 3.0.0\npaths:\n  /a:\n    get:\n    get:\n":             `line 5: duplicate key "get"`,
		"openapi: 3.0.0\n---\npaths:\n":                                   "line 2: several documents or a directive",
		"openapi: 3.0.0\npaths:\n\t/a:\n":                                 "line 3: tab indentation",
		"openapi: 3.0.0\n<<: x\n":                                         "line 2: merge key",
		"openapi: 3.0.0\ntitle: !!str x\n":                                "line 2: tag",
		"- a\n":                                                           "no top-level mapping",
		"openapi: 3.0.0\npaths:\n  /a:\n    get:\n      summary: 'open\n": "line 5: unterminated quoted scalar",
	} {
		if _, reason, detail := openAPIEndpoints("o.yaml", []byte(src)); reason != "openapi-yaml-unsupported" || detail != want {
			t.Errorf("%q: %q %q, want %q", src, reason, detail, want)
		}
	}
}

// AMAP-V0-220: impact places a changed Rails controller on the screens calling its endpoints under
// basis endpoint:ID. An endpoint no read call reaches, a join with any unknown, and a changed
// declaration file stay unknown; without the join inputs the controller stays non-ui-path.
func TestAMAPV0220ImpactThroughEndpoints(t *testing.T) {
	routes := "Rails.application.routes.draw do\n  get \"api/clubs/:club_id/settings\", to: \"settings#show\"\n  patch \"api/clubs/:club_id/settings\", to: \"settings#update\"\nend\n"
	ctrl := "angular.module('admin').controller('SettingsCtrl', ['$http', '$stateParams', function ($http, $stateParams) {\n" +
		"  $http.get('/api/clubs/' + $stateParams.clubId + '/settings');\n%s}]);\n"
	f := hopRepo(t, map[string]string{"config/routes.rb": routes, "app/controllers/settings_controller.rb": "class SettingsController\nend\n",
		"app/models/club.rb": "class Club\nend\n", "app/clubs/settings.ctrl.js": strings.Replace(ctrl, "%s", "", 1)})
	eo := &EndpointsOptions{RailsRoutes: []string{"config/routes.rb"}, Sources: []string{"app/clubs"}}
	settings, controller := screenID("admin", "app.clubs.settings"), "app/controllers/settings_controller.rb"
	unknowns := func(r ImpactReport, p string) []string {
		out := []string{}
		for _, u := range r.Unknown {
			if u.Path == p {
				out = append(out, u.Reason+" "+u.Detail)
			}
		}
		return out
	}
	hit := func(r ImpactReport, p string) string {
		for _, s := range r.Screens {
			if s.ID == settings && len(s.Paths) > 0 && s.Paths[0] == p {
				return s.Basis
			}
		}
		return ""
	}
	change := func(files map[string]string, rebuild bool, o Options) ImpactReport {
		t.Helper()
		base := gitTest(t, f.root, "rev-parse", "HEAD")
		if rebuild {
			f.m = build(t, f.root, base)
		}
		impactCommit(t, f, files)
		return impactRun(t, f, nil, base, o)
	}
	edit := map[string]string{controller: "class SettingsController\n  def show; end\nend\n", "app/models/club.rb": "class Club; end\n"}
	r := change(edit, false, Options{})
	if got := unknowns(r, controller); strings.Join(got, ",") != "non-ui-path " || hit(r, controller) != "" {
		t.Fatalf("without endpoints: %v %+v", got, r.Screens)
	}
	edit[controller] += "# again\n"
	edit["app/models/club.rb"] += "# again\n"
	r = change(edit, false, Options{Endpoints: eo})
	if hit(r, controller) != "endpoint:GET /api/clubs/{}/settings" || strings.Join(unknowns(r, controller), ",") != "endpoint-not-called PATCH /api/clubs/{}/settings" ||
		strings.Join(unknowns(r, "app/models/club.rb"), ",") != "non-ui-path " || r.Verdict != VerdictFullSuite {
		t.Fatalf("one endpoint uncalled: %+v", r)
	}
	impactCommit(t, f, map[string]string{"app/clubs/settings.ctrl.js": strings.Replace(ctrl, "%s", "  $http.patch('/api/clubs/' + id + '/settings', body);\n", 1)})
	r = change(map[string]string{controller: "class SettingsController\nend\n"}, true, Options{Endpoints: eo})
	if hit(r, controller) == "" || len(unknowns(r, controller)) != 0 {
		t.Fatalf("every endpoint called, join complete: %+v", r)
	}
	// AMAP-V0-355: a changed route file is compared at base and head; a comment-only change
	// places nothing, and only the removed and added endpoints are reported.
	r = change(map[string]string{"config/routes.rb": routes + "# routes\n"}, false, Options{Endpoints: eo})
	if hit(r, "config/routes.rb") != "" || len(unknowns(r, "config/routes.rb")) != 0 {
		t.Fatalf("comment-only declaration change: %+v", r)
	}
	swapped := strings.Replace(routes, "  patch \"api/clubs/:club_id/settings\", to: \"settings#update\"\n",
		"  post \"api/clubs/:club_id/members\", to: \"members#create\"\n", 1)
	r = change(map[string]string{"config/routes.rb": swapped}, false, Options{Endpoints: eo})
	if hit(r, "config/routes.rb") != "endpoint-removed:PATCH /api/clubs/{}/settings" ||
		strings.Join(unknowns(r, "config/routes.rb"), ",") != "endpoint-not-called added POST /api/clubs/{}/members" {
		t.Fatalf("declaration change: %v %+v", unknowns(r, "config/routes.rb"), r)
	}
	r = change(map[string]string{"config/routes.rb": swapped + "if ENV[\"X\"]\n  get \"x\", to: \"x#y\"\nend\n"}, false, Options{Endpoints: eo})
	if got := unknowns(r, "config/routes.rb"); len(got) != 1 || !strings.HasPrefix(got[0], "endpoint-declaration-changed the base and head endpoint comparison is partial, first config/routes.rb:5 rails-region-not-read") {
		t.Fatalf("partial comparison: %v", got)
	}
	impactCommit(t, f, map[string]string{"config/routes.rb": routes})
	// AMAP-V0-355: a changed constraint changes the requests an endpoint serves, and so does a
	// swap of two endpoints one request may match; a swap of endpoints no request shares does not.
	constrained := strings.Replace(routes, `to: "settings#show"`, `to: "settings#show", constraints: {club_id: /\d+/}`, 1)
	for _, next := range []string{constrained, strings.Replace(constrained, `/\d+/`, `/\d{2}/`, 1), routes} {
		r = change(map[string]string{"config/routes.rb": next}, false, Options{Endpoints: eo})
		if hit(r, "config/routes.rb") != "endpoint:GET /api/clubs/{}/settings" || len(unknowns(r, "config/routes.rb")) != 0 {
			t.Fatalf("constraint change: %v %+v", unknowns(r, "config/routes.rb"), r)
		}
	}
	getLine, patchLine := "  get \"api/clubs/:club_id/settings\", to: \"settings#show\"\n", "  patch \"api/clubs/:club_id/settings\", to: \"settings#update\"\n"
	r = change(map[string]string{"config/routes.rb": strings.Replace(routes, getLine+patchLine, patchLine+getLine, 1)}, false, Options{Endpoints: eo})
	if hit(r, "config/routes.rb") != "" || len(unknowns(r, "config/routes.rb")) != 0 {
		t.Fatalf("disjoint swap: %v %+v", unknowns(r, "config/routes.rb"), r)
	}
	featured := "  get \"api/clubs/featured/settings\", to: \"featured#show\"\n"
	impactCommit(t, f, map[string]string{"config/routes.rb": strings.Replace(routes, getLine, getLine+featured, 1)})
	r = change(map[string]string{"config/routes.rb": strings.Replace(routes, getLine, featured+getLine, 1)}, false, Options{Endpoints: eo})
	if got := hit(r, "config/routes.rb"); !strings.HasPrefix(got, "endpoint:GET /api/clubs/") || len(unknowns(r, "config/routes.rb")) != 0 {
		t.Fatalf("overlapping swap: %q %v %+v", got, unknowns(r, "config/routes.rb"), r)
	}
	// AMAP-V0-355: a listed router the change adds (a map at base) or deletes (a map at head) is
	// absent at the map revision and read there as declaring nothing; one absent at both sides
	// still refuses.
	impactCommit(t, f, map[string]string{"config/routes.rb": routes})
	two := &EndpointsOptions{RailsRoutes: []string{"config/routes.rb", "config/audit_routes.rb"}, Sources: eo.Sources}
	audit := "Rails.application.routes.draw do\n  get \"api/clubs/:club_id/settings/audit\", to: \"audits#show\"\nend\n"
	r = change(map[string]string{"config/audit_routes.rb": audit}, true, Options{Endpoints: two})
	if got := unknowns(r, "config/audit_routes.rb"); strings.Join(got, ",") != "endpoint-not-called added GET /api/clubs/{}/settings/audit" {
		t.Fatalf("added router: %v %+v", got, r)
	}
	before := gitTest(t, f.root, "rev-parse", "HEAD")
	if err := os.Remove(filepath.Join(f.root, "config/audit_routes.rb")); err != nil {
		t.Fatal(err)
	}
	after := commitAll(t, f.root, "delete router")
	f.m = build(t, f.root, after)
	r = impactRun(t, f, nil, before, Options{Endpoints: two})
	if got := unknowns(r, "config/audit_routes.rb"); strings.Join(got, ",") != "endpoint-not-called removed GET /api/clubs/{}/settings/audit" {
		t.Fatalf("deleted router: %v %+v", got, r)
	}
	impactCommit(t, f, map[string]string{controller: "class SettingsController\n  # y\nend\n"})
	if _, err := Impact(context.Background(), f.m, nil, after, Options{Root: f.root, Endpoints: two}); err == nil {
		t.Fatal("a router absent at the map revision and unchanged is refused")
	}
	impactCommit(t, f, map[string]string{"app/clubs/other.js": "fetch(url);\n"})
	r = change(map[string]string{controller: "class SettingsController\n  # x\nend\n"}, true, Options{Endpoints: eo})
	got := unknowns(r, controller)
	if hit(r, controller) == "" || len(got) != 1 || !strings.HasPrefix(got[0], "endpoint-callers-incomplete 1 endpoint join unknowns, first app/clubs/other.js:1 non-literal-url") {
		t.Fatalf("incomplete join: %v %+v", got, r)
	}
	for _, u := range r.Unknown {
		if u.Path == controller && (u.Remedy == nil || u.Remedy.Key != "") {
			t.Fatalf("remedy: %+v", u)
		}
	}
}

// AMAP-V0-221: an OpenAPI path item that is a $ref is not followed; the document yields no endpoint
// and an openapi-path-ref-not-read unknown naming the path, in JSON and YAML alike, so the join is
// never reported complete while omitting the referenced operations.
func TestAMAPV0221OpenAPIPathRefUnknown(t *testing.T) {
	for file, src := range map[string]string{
		"o.json": `{"openapi":"3.1.0","paths":{"/a":{"get":{}},"/b":{"$ref":"#/components/pathItems/B"}}}`,
		"o.yaml": "openapi: 3.1.0\npaths:\n  /a:\n    get:\n      operationId: a\n  /b:\n    $ref: 'other.yaml#/B'\n",
	} {
		rows, reason, detail := openAPIEndpoints(file, []byte(src))
		if len(rows) != 0 || reason != "openapi-path-ref-not-read" || detail != "/b" {
			t.Errorf("%s: %+v %q %q", file, rows, reason, detail)
		}
	}
}
