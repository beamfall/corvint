func docsRepository(t *testing.T) string {
	t.Helper()
	root := taskContextRepository(t)
	owner := "# Cache\nDelivery status: experimental\n\n## Agent digest\n- Claim: splits keys\n- Blocked on: behavior validation\n\n## Requirements\nNever promote drafts.\n"
	for name, text := range map[string]string{"owner.md": owner, "generated.md": "<!-- Code generated by fixture. DO NOT EDIT. -->\n" + owner} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(text), 0644); err != nil {
			t.Fatal(err)
		}
	}
	docsCommit(t, root)
	return root
}

func docsCommit(t *testing.T, root string) {
	t.Helper()
	for _, args := range [][]string{{"add", "-A"}, {"-c", "user.name=t", "-c", "user.email=t@x", "commit", "-qm", "docs fixture"}} {
		command := exec.Command("git", args...)
		command.Dir = root
		if output, err := command.CombinedOutput(); err != nil {
			t.Fatalf("git: %v %s", err, output)
		}
	}
}

func runDocsFixture(t *testing.T, root, mode, input string, extra ...string) (int, string, string) {
	t.Helper()
	args := []string{"--root", root, "docs", mode, "--source", "owner.md", "--package", "cache"}
	args = append(args, extra...)
	var out, err bytes.Buffer
	code := runContext(context.Background(), args, strings.NewReader(input), &out, &err)
	return code, out.String(), err.String()
}

func TestDocsCLIActualDraftConsumeReadOnlyAndImmutable(t *testing.T) {
	t.Parallel()
	t.Run("SDD-V0-001", func(t *testing.T) {
		root := docsRepository(t)
		before := repositoryListing(t, root)
		code, draft, stderr := runDocsFixture(t, root, "draft", "")
		if code != 0 {
			t.Fatalf("draft exit %d: %s", code, stderr)
		}
		code, output, stderr := runDocsFixture(t, root, "consume", draft, "--task", "Split")
		if code != 0 {
			t.Fatalf("consume exit %d: %s", code, stderr)
		}
		var result struct {
			State, Behavior, Validation string
			Results                     []struct{ Path, Excerpt string }
		}
		if err := json.Unmarshal([]byte(output), &result); err != nil {
			t.Fatal(err)
		}
		if result.State != "READY" || result.Behavior != "UNKNOWN" || result.Validation != "SOURCE_REDERIVED" || len(result.Results) != 1 || result.Results[0].Path != "cache/demux.go" {
			t.Fatalf("result: %s", output)
		}
		if after := repositoryListing(t, root); after != before {
			t.Fatal("docs wrote repository state")
		}
		if err := os.WriteFile(filepath.Join(root, "cache/demux.go"), []byte("package cache\nfunc DirtyOnly() {}\n"), 0644); err != nil {
			t.Fatal(err)
		}
		code, dirty, stderr := runDocsFixture(t, root, "draft", "")
		if code != 0 || dirty != draft {
			t.Fatalf("dirty bytes influenced evidence: %d %s", code, stderr)
		}
		docsCommit(t, root)
		code, output, stderr = runDocsFixture(t, root, "consume", draft, "--task", "Split")
		if code != 2 || output != "" || !strings.Contains(stderr, "stale-documentation-draft") {
			t.Fatalf("stale draft: %d %q %s", code, output, stderr)
		}
	})
}

