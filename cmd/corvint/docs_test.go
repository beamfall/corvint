func TestDocsCLIAddedImporterInvalidatesPriorDraft(t *testing.T) {
	t.Parallel()
	root := docsRepository(t)
	code, prior, stderr := runDocsFixture(t, root, "draft", "")
	if code != 0 {
		t.Fatalf("draft exit %d: %s", code, stderr)
	}
	original, err := os.ReadFile(filepath.Join(root, "cache/demux.go"))
	if err != nil {
		t.Fatal(err)
	}
	module, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	modulePath := strings.Fields(string(module))[1]
	if err := os.Mkdir(filepath.Join(root, "newconsumer"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "newconsumer/new.go"), []byte("package newconsumer\nimport _ \""+modulePath+"/cache\"\n"), 0644); err != nil {
		t.Fatal(err)
	}
	docsCommit(t, root)
	after, err := os.ReadFile(filepath.Join(root, "cache/demux.go"))
	if err != nil || !bytes.Equal(original, after) {
		t.Fatal("fixture changed the original package")
	}
	code, fresh, stderr := runDocsFixture(t, root, "draft", "")
	if code != 0 || !strings.Contains(fresh, "newconsumer/new.go") {
		t.Fatalf("new import missing: %d %s", code, stderr)
	}
	code, output, stderr := runDocsFixture(t, root, "consume", prior, "--task", "Split")
	if code != 2 || output != "" || !strings.Contains(stderr, "stale-documentation-draft") {
		t.Fatalf("prior draft accepted: %d %q %s", code, output, stderr)
	}
}

func TestDocsCLIRejectsExecutableGitFiltersWithoutMutation(t *testing.T) {
	t.Parallel()
	for _, mode := range []string{"draft", "consume"} {
		t.Run(mode, func(t *testing.T) {
			root := docsRepository(t)
			code, draft, stderr := runDocsFixture(t, root, "draft", "")
			if code != 0 {
				t.Fatal(stderr)
			}
			if err := os.WriteFile(filepath.Join(root, ".gitattributes"), []byte("*.go filter=docs_audit\n"), 0644); err != nil {
				t.Fatal(err)
			}
			marker := filepath.Join(root, "unexpected-filter-execution")
			filter := ": > '" + strings.ReplaceAll(marker, "'", "'\"'\"'") + "'; cat"
			command := exec.Command("git", "-C", root, "config", "filter.docs_audit.clean", filter)
			if output, err := command.CombinedOutput(); err != nil {
				t.Fatalf("configure fixture: %v %s", err, output)
			}
			source := filepath.Join(root, "cache", "demux.go")
			original, err := os.ReadFile(source)
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(source, bytes.ReplaceAll(original, []byte("Split"), []byte("SpLit")), 0644); err != nil {
				t.Fatal(err)
			}
			oldTime := time.Unix(1700000000, 0)
			if err := os.Chtimes(source, oldTime, oldTime); err != nil {
				t.Fatal(err)
			}
			before := repositoryBytesDigest(t, root)
			var extra []string
			if mode == "consume" {
				extra = []string{"--task", "Split"}
			}
			code, output, stderr := runDocsFixture(t, root, mode, draft, extra...)
			if code == 0 || output != "" || stderr == "" {
				t.Fatalf("unsafe Git configuration admitted: %d %q %q", code, output, stderr)
			}
			if _, err := os.Stat(marker); !os.IsNotExist(err) {
				t.Fatalf("Git executed the repository's filter: %v", err)
			}
			if after := repositoryBytesDigest(t, root); after != before {
				t.Fatal("refused documentation operation mutated the repository")
			}
		})
	}
}

